#ifndef CERT_CHAIN_VERIFIER_INTERFACE_H_
#define CERT_CHAIN_VERIFIER_INTERFACE_H_

#include <stddef.h>
#include <stdint.h>
#include "common/certificate.h"
#include "status/rot_status.h"


/**
 * Verified alias key and root certificate.  A successful finalize_verification transfers ownership
 * of both DER buffers to this struct; the caller must free them with
 * cert_chain_verifier_result_release.  key_type identifies the alias key algorithm; the caller
 * materializes the key with the matching crypto engine.
 */
struct cert_chain_verifier_result {
	int key_type;				/**< X509_PUBLIC_KEY_ECC or X509_PUBLIC_KEY_RSA. */
	const uint8_t *alias_key;	/**< Owned leaf public key DER. */
	size_t alias_key_length;	/**< Length of alias_key in bytes. */
	struct der_cert root_cert;	/**< Owned root certificate (DER). */
};

/**
 * Root-first streaming certificate chain verifier.  The caller checks chain completeness,
 * endpoint selection, and root trust; this interface checks chain integrity and extracts the key.
 *
 * Usage flow:
 * - start_verification
 * - one or more process_cert calls, root first
 * - finalize_verification
 */
struct cert_chain_verifier {
	/**
	 * Begin a new chain, discarding prior state and invalidating any borrowed root certificate.
	 *
	 * @param verifier The certificate chain verifier.
	 *
	 * @return 0 on success or an error code.
	 */
	int (*start_verification) (const struct cert_chain_verifier *verifier);

	/**
	 * Process the next certificate, root first.  The cert buffer must not be modified until the
	 * call returns; it may be reused afterward.  A failure aborts the whole verification: the chain
	 * is discarded and the caller must begin again with start_verification.
	 *
	 * @param verifier The certificate chain verifier.
	 * @param cert The certificate DER bytes.
	 * @param length Length of cert in bytes.
	 *
	 * @return 0 on success or an error code.
	 */
	int (*process_cert) (const struct cert_chain_verifier *verifier, const uint8_t *cert,
		size_t length);

	/**
	 * Transfer the last authenticated non-root certificate's key and the root certificate to the
	 * caller.  The caller must confirm the whole chain was consumed and that the last certificate is
	 * the expected leaf before this call.  On success, ownership of both buffers in result moves to
	 * the caller (free them with cert_chain_verifier_result_release) and the verifier returns to
	 * an idle state, ready for the next start_verification; a second finalize_verification without a
	 * new start returns CERT_CHAIN_VERIFIER_NOT_STARTED.  A failure aborts the whole verification:
	 * the chain is discarded and the caller must begin again with start_verification.
	 *
	 * @param verifier The certificate chain verifier.
	 * @param result Verification result.  Set only on success.
	 *
	 * @return 0 on success, CERT_CHAIN_VERIFIER_INCOMPLETE_CHAIN if no non-root certificate was
	 * accepted, or another error code.
	 */
	int (*finalize_verification) (const struct cert_chain_verifier *verifier,
		struct cert_chain_verifier_result *result);
};


void cert_chain_verifier_result_release (struct cert_chain_verifier_result *result);


#define	CERT_CHAIN_VERIFIER_ERROR(code)		ROT_ERROR (ROT_MODULE_CERT_CHAIN_VERIFIER, code)

/**
 * Error codes that can be generated by a certificate chain verifier.
 */
enum {
	CERT_CHAIN_VERIFIER_INVALID_ARGUMENT = CERT_CHAIN_VERIFIER_ERROR (0x00),				/**< Input parameter is null or not valid. */
	CERT_CHAIN_VERIFIER_NO_MEMORY = CERT_CHAIN_VERIFIER_ERROR (0x01),						/**< Memory allocation failed. */
	CERT_CHAIN_VERIFIER_NOT_STARTED = CERT_CHAIN_VERIFIER_ERROR (0x02),						/**< process_cert / finalize before start_verification. */
	CERT_CHAIN_VERIFIER_ROOT_TOO_LARGE = CERT_CHAIN_VERIFIER_ERROR (0x03),					/**< Root certificate exceeds the supported size. */
	CERT_CHAIN_VERIFIER_CHAIN_INVALID = CERT_CHAIN_VERIFIER_ERROR (0x04),					/**< A certificate failed authentication against the trust anchor. */
	CERT_CHAIN_VERIFIER_INCOMPLETE_CHAIN = CERT_CHAIN_VERIFIER_ERROR (0x05),				/**< finalize_verification before a non-root certificate was accepted. */
	CERT_CHAIN_VERIFIER_NO_KEY = CERT_CHAIN_VERIFIER_ERROR (0x06),							/**< The leaf public key could not be extracted. */
	CERT_CHAIN_VERIFIER_START_VERIFICATION_FAILED = CERT_CHAIN_VERIFIER_ERROR (0x07),		/**< Failed to start certificate chain verification. */
	CERT_CHAIN_VERIFIER_PROCESS_CERT_FAILED = CERT_CHAIN_VERIFIER_ERROR (0x08),				/**< Failed to process a certificate in the chain. */
	CERT_CHAIN_VERIFIER_FINALIZE_VERIFICATION_FAILED = CERT_CHAIN_VERIFIER_ERROR (0x09),	/**< Failed to finalize certificate chain verification. */
	CERT_CHAIN_VERIFIER_NO_TRUST_ANCHOR = CERT_CHAIN_VERIFIER_ERROR (0x0a),					/**< No trust anchor was available to validate the next certificate. */
};


#endif	/* CERT_CHAIN_VERIFIER_INTERFACE_H_ */
