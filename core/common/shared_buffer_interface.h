#ifndef SHARED_BUFFER_INTERFACE_H_
#define SHARED_BUFFER_INTERFACE_H_

#include <stddef.h>
#include <stdint.h>
#include "status/rot_status.h"


/**
 * Handle returned by a successful lock call and used to release the region.
 */
struct shared_buffer_handle {
	void *ptr;			/**< Buffer region.  Valid only while the lock is held. */
	size_t size;		/**< Region size, in bytes. */
	uintptr_t owner;	/**< Owner tag used to validate unlock. */
};

/**
 * Protocol-agnostic hand-off contract for a single buffer region shared by independent consumers.
 * Only one consumer may hold the region at a time.
 */
struct shared_buffer_interface {
	/**
	 * Get the total size of the buffer region.  The region size is invariant, so this is safe to
	 * call without holding the lock: it exposes capacity for sizing / early-rejection decisions
	 * without granting access to the bytes.
	 *
	 * @param buffer The shared buffer to query.
	 * @param size Output for the region size, in bytes.
	 *
	 * @return 0 if the size was returned successfully or an error code.
	 */
	int (*get_buffer_size) (const struct shared_buffer_interface *buffer, size_t *size);

	/**
	 * Acquire exclusive access to the buffer region.
	 *
	 * @param buffer The shared buffer to acquire.
	 * @param handle Output for the handle granting access to the region.  Valid only on success and
	 * only until the matching unlock.
	 *
	 * @return 0 if the buffer was acquired successfully or an error code.  SHARED_BUFFER_BUSY is
	 * returned if the buffer is already held.
	 */
	int (*lock) (const struct shared_buffer_interface *buffer, struct shared_buffer_handle *handle);

	/**
	 * Release access previously acquired through lock.  On success the handle is cleared: its region
	 * pointer is zeroed so a buggy caller that reuses it faults instead of touching a region now
	 * owned by someone else, and a repeated unlock of the same handle is rejected.
	 *
	 * @param buffer The shared buffer to release.
	 * @param handle The handle returned by the matching lock call.  Cleared on success.
	 *
	 * @return 0 if the buffer was released successfully or an error code.  SHARED_BUFFER_NOT_HELD is
	 * returned if the buffer is not currently held; SHARED_BUFFER_WRONG_OWNER is returned if the
	 * handle does not match the current holder.
	 */
	int (*unlock) (const struct shared_buffer_interface *buffer,
		struct shared_buffer_handle *handle);
};


#define SHARED_BUFFER_ERROR(code)	ROT_ERROR (ROT_MODULE_SHARED_BUFFER, code)

/**
 * Error codes that can be generated by a shared buffer.
 */
enum {
	SHARED_BUFFER_INVALID_ARGUMENT = SHARED_BUFFER_ERROR (0x00),		/**< Input parameter is null or not valid. */
	SHARED_BUFFER_NO_MEMORY = SHARED_BUFFER_ERROR (0x01),				/**< Memory allocation failed. */
	SHARED_BUFFER_BUSY = SHARED_BUFFER_ERROR (0x02),					/**< The buffer is already held by another consumer. */
	SHARED_BUFFER_NOT_HELD = SHARED_BUFFER_ERROR (0x03),				/**< Unlock attempted while the buffer is not held. */
	SHARED_BUFFER_WRONG_OWNER = SHARED_BUFFER_ERROR (0x04),				/**< Unlock attempted with a handle that is not the current holder. */
	SHARED_BUFFER_GET_BUFFER_SIZE_FAILED = SHARED_BUFFER_ERROR (0x05),	/**< Generic failure from shared_buffer_interface.get_buffer_size. */
	SHARED_BUFFER_LOCK_FAILED = SHARED_BUFFER_ERROR (0x06),				/**< Generic failure from shared_buffer_interface.lock. */
	SHARED_BUFFER_UNLOCK_FAILED = SHARED_BUFFER_ERROR (0x07),			/**< Generic failure from shared_buffer_interface.unlock. */
};


#endif	/* SHARED_BUFFER_INTERFACE_H_ */
