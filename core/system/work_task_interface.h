#ifndef WORK_TASK_INTERFACE_H_
#define WORK_TASK_INTERFACE_H_

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include "platform_api.h"
#include "status/rot_status.h"


struct work_task_interface;
struct work_task_entry;

/**
 * A handler that can be queued on a work task for execution.
 */
struct work_task_handler {
	/**
	 * Execute the handler.  Called from the work task context with the entry detached, so the
	 * handler may re-queue the entry it is running.
	 *
	 * @param handler The handler being executed.  This will never be null.
	 * @param task The task executing this invocation.  This will never be null.  A shared handler
	 * must use this parameter rather than cache a task pointer in shared handler state.
	 * @param context Caller-supplied payload from the queued entry.  May be null.
	 */
	void (*execute) (const struct work_task_handler *handler,
		const struct work_task_interface *task,	void *context);
};

/**
 * A caller-owned entry that binds a handler to a work task.  The caller provides the storage; all
 * fields are managed by the task.  An entry must be zero-initialized before its first use.
 */
struct work_task_entry {
	const struct work_task_handler *handler;	/**< Handler to invoke.  Bound at submit/schedule. */
	void *context;								/**< Opaque payload passed to the handler. */
	platform_clock next_execution;				/**< Earliest time the entry may run when scheduled. */
	struct work_task_entry *next;				/**< Intrusive list linkage. */
	const struct work_task_interface *owner;	/**< Task the entry is queued on, or null. */
	bool is_scheduled;							/**< True when next_execution holds a deadline. */
	uint8_t priority;							/**< Higher values run before lower ones. */
};

/**
 * Interface to a task that runs queued work, either immediately or at a scheduled time.
 */
struct work_task_interface {
	/**
	 * Queue an entry to run at priority zero as soon as the task is available.  An entry already
	 * pending on any task is rejected without changing its handler or context.
	 *
	 * @param task The initialized task to submit to.
	 * @param entry The caller-owned entry to queue, zero-initialized before first use.
	 * @param handler The handler to invoke for the entry.
	 * @param context Opaque payload passed to the handler.  May be null.
	 *
	 * @return 0 if the entry was queued, WORK_TASK_ALREADY_QUEUED if it is already pending, or
	 * an error code.  Success does not indicate handler completion.
	 */
	int (*submit) (const struct work_task_interface *task, struct work_task_entry *entry,
		const struct work_task_handler *handler, void *context);

	/**
	 * Queue an entry at priority zero to run no earlier than a given time.  A null deadline makes
	 * the entry ready immediately.  The deadline does not guarantee when the handler will run.
	 * An entry already pending on any task is rejected without changing its binding or deadline.
	 *
	 * @param task The initialized task to submit to.
	 * @param entry The caller-owned entry to queue, zero-initialized before first use.
	 * @param handler The handler to invoke for the entry.
	 * @param context Opaque payload passed to the handler.  May be null.
	 * @param next_execution The earliest time the entry may run, copied into the entry, or null
	 * for immediate execution.
	 *
	 * @return 0 if the entry was queued, WORK_TASK_ALREADY_QUEUED if it is already pending, or
	 * an error code.  Success does not indicate handler completion.
	 */
	int (*schedule) (const struct work_task_interface *task, struct work_task_entry *entry,
		const struct work_task_handler *handler, void *context,
		const platform_clock *next_execution);

	/**
	 * Remove a pending entry from the task.  Cancellation does not stop or wait for an executing
	 * handler and is not a completion barrier.  If a running entry has been requeued, only the
	 * pending execution is removed.
	 *
	 * @param task The initialized task holding the entry.
	 * @param entry The entry to cancel.
	 *
	 * @return 0 if the entry was removed, WORK_TASK_NOT_QUEUED if it is not pending,
	 * WORK_TASK_FOREIGN_ENTRY if it belongs to another task, or an error code.
	 */
	int (*cancel) (const struct work_task_interface *task, struct work_task_entry *entry);
};


#define	WORK_TASK_ERROR(code)		ROT_ERROR (ROT_MODULE_WORK_TASK, code)

/**
 * Error codes that can be generated by a work task.
 */
enum {
	WORK_TASK_INVALID_ARGUMENT = WORK_TASK_ERROR (0x00),	/**< Input parameter is null or not valid. */
	WORK_TASK_NO_MEMORY = WORK_TASK_ERROR (0x01),			/**< Memory allocation failed. */
	WORK_TASK_ALREADY_QUEUED = WORK_TASK_ERROR (0x02),		/**< The entry is already queued. */
	WORK_TASK_FOREIGN_ENTRY = WORK_TASK_ERROR (0x03),		/**< The entry is owned by a different task. */
	WORK_TASK_NOT_QUEUED = WORK_TASK_ERROR (0x04),			/**< The entry is not queued. */
	WORK_TASK_SUBMIT_FAILED = WORK_TASK_ERROR (0x05),		/**< Failed to submit an entry. */
	WORK_TASK_SCHEDULE_FAILED = WORK_TASK_ERROR (0x06),		/**< Failed to schedule an entry. */
	WORK_TASK_CANCEL_FAILED = WORK_TASK_ERROR (0x07),		/**< Failed to cancel an entry. */
	WORK_TASK_RUN_FAILED = WORK_TASK_ERROR (0x08),			/**< Failed to run a queued entry. */
	WORK_TASK_INIT_FAILED = WORK_TASK_ERROR (0x09),			/**< Failed to initialize the work task. */
};


#endif	/* WORK_TASK_INTERFACE_H_ */
